/**
 * Reads and writes myst config through the `yaml` Document API, which keeps the author's keys,
 * order and comments; never a text patch [R3].
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { isMap, isSeq, parseDocument, type Document, type YAMLError } from 'yaml';
import { BRAND_ASSET_KEYS, type OwnOverride } from './compose.js';
import { EDITION_ID, JournalConfig, JournalStamp } from './schema.js';
import * as msg from './messages.js';
import { firstLine, UserError } from './messages.js';

/**
 * The derived config oak builds from [R71]: the author's `myst.yml` plus the `extends:` chain
 * and compose's additions. It sits at the paper root because myst resolves `toc`,
 * `bibliography`, plugins and brand assets relative to the config. It is not deleted after a
 * build, since myst exits the process on success [R67.3]; the paper template gitignores it.
 */
export const DERIVED_CONFIG_FILE = 'myst.oak.yml';

const DERIVED_BANNER =
  ' GENERATED by `oak build`: do not edit, do not commit.\n' +
  ' Your config is `myst.yml`; this is it composed with the engine/edition/brand chain.\n' +
  ' Regenerated on every build; safe to delete.';

/** Where oak writes the {@link JournalStamp}: beside the version and edition. */
const JOURNAL_KEY = ['project', 'options', 'oaktree-sapling', 'journal'];

/**
 * The journal stamp oak wrote into `<paperRoot>/myst.oak.yml`: the stamp, null when the build
 * had no journal, undefined when there is no derived config or the value is not a valid stamp.
 * Parsed with the schema: in CI the file comes from the build job's artifact.
 */
export function readJournalStamp(paperRoot: string): JournalStamp | null | undefined {
  const path = join(paperRoot, DERIVED_CONFIG_FILE);
  if (!existsSync(path)) return undefined;
  const raw = readDoc(path).getIn(JOURNAL_KEY);
  if (raw === undefined) return null;
  const parsed = JournalStamp.safeParse(isMap(raw) ? raw.toJSON() : raw);
  return parsed.success ? parsed.data : undefined;
}

/** Whether the author's `<paperRoot>/myst.yml` sets the key oak writes ({@link JournalStamp}). */
export function authorSetsJournalStamp(paperRoot: string): boolean {
  const path = join(paperRoot, 'myst.yml');
  if (!existsSync(path)) return false;
  try {
    return readDoc(path).hasIn(JOURNAL_KEY);
  } catch {
    return false;
  }
}

/** Drops an author's {@link JournalStamp} before pass 1, so only oak's reaches the build. */
export function dropJournalStamp(doc: Document): void {
  if (doc.hasIn(JOURNAL_KEY)) doc.deleteIn(JOURNAL_KEY);
}

/**
 * Parses YAML into a Document, or throws a {@link UserError} naming `source` when the parser
 * reports an error: a duplicate key, bad indentation, a second document. Every YAML oak reads
 * goes through here, so each verb accepts and refuses the same files. Warnings (an unknown tag,
 * an ambiguous alias) leave every value defined, so they pass.
 */
export function parseYaml(text: string, source: string): Document {
  const doc = parseDocument(text);
  const first = doc.errors[0];
  if (first) throw new UserError(yamlRefusal(first, text, source));
  return doc;
}

/** The refusal for a parser error: a plain cause for the errors authors commonly make, the
 *  parser's own first line for the rest. */
function yamlRefusal(e: YAMLError, text: string, source: string): string {
  const lines = text.split(/\r?\n/);
  const { line, col } = e.linePos?.[0] ?? { line: 1, col: 1 };
  switch (e.code) {
    case 'MULTIPLE_DOCS': {
      // The parser points where the second document starts, at or after its marker line.
      let at = line;
      while (at > 1 && !/^(---|\.\.\.)(\s|$)/.test(lines[at - 1] ?? '')) at--;
      return msg.yamlMultipleDocs(source, at, lines[at - 1]?.startsWith('...') ? '...' : '---');
    }
    case 'MULTILINE_IMPLICIT_KEY':
      return msg.yamlNotKeyValue(source, line);
    case 'BLOCK_AS_IMPLICIT_KEY':
      // The same code covers other shapes, which keep the parser's text.
      if ((lines[line - 1] ?? '').slice(col - 1).includes(': ')) {
        return msg.yamlColonInValue(source, line);
      }
  }
  const why = firstLine(e).replace(/:$/, '');
  return msg.yamlInvalid(source, why, e.code === 'DUPLICATE_KEY');
}

/** Reads a YAML file through {@link parseYaml}. */
export function readDoc(path: string): Document {
  return parseYaml(readFileSync(path, 'utf8'), path);
}

/** The journal's settings from `<instanceRoot>/journal.yml`, checked against
 *  {@link JournalConfig}, or null when the file is absent. Throws a {@link UserError} naming the
 *  file for bad YAML or a bad setting. */
export function readJournalConfig(instanceRoot: string): JournalConfig | null {
  const path = join(instanceRoot, 'journal.yml');
  if (!existsSync(path)) return null;
  const parsed = JournalConfig.safeParse(readDoc(path).toJS() ?? {});
  if (!parsed.success) throw new UserError(msg.journalInvalid(path, firstLine(parsed.error)));
  return parsed.data;
}

export function writeDoc(path: string, doc: Document): void {
  writeFileSync(path, doc.toString());
}

/** Writes the derived config with a banner saying it is generated from `myst.yml`. */
export function writeDerivedDoc(path: string, doc: Document): void {
  doc.commentBefore = DERIVED_BANNER;
  writeFileSync(path, doc.toString());
}

/** Reads the version and edition from the author's myst.yml before any merge, as the engine
 *  action does, so it works before the journal is resolved [design §6a]. A missing value is the
 *  author's to fix, so it throws a {@link UserError} naming the file. */
export function readEngineCoordinateRaw(
  doc: Document,
  mystPath = 'myst.yml',
): { version: string; edition: string } {
  const version = doc.getIn(['project', 'options', 'oaktree-sapling', 'version']);
  const edition = doc.getIn(['project', 'options', 'oaktree-sapling', 'edition']);
  if (typeof version !== 'string' || !version) {
    throw new UserError(msg.build.missingEngineCoordinate('version', mystPath));
  }
  if (typeof edition !== 'string' || !edition) {
    throw new UserError(msg.build.missingEngineCoordinate('edition', mystPath));
  }
  // Checked here too: this value picks a file in `extendsChainFor` before anything validates the
  // merged config [R141].
  if (!EDITION_ID.safeParse(edition).success) {
    throw new UserError(msg.build.badEdition(edition, mystPath));
  }
  return { version, edition };
}

/** Reads the asset fields from `<instanceRoot>/brand/brand.yml` itself, not the merged config,
 *  so only the brand's own assets are resolved against the journal root and a paper's relative
 *  path is left alone [R62]. Returns `site.options` (HTML) and `project.options.logo` (the PDF
 *  watermark); empty when absent. */
export function readBrandAssetOptions(instanceRoot: string): {
  site: Record<string, string>;
  project: Record<string, string>;
} {
  const brandPath = join(instanceRoot, 'brand', 'brand.yml');
  const empty = { site: {}, project: {} };
  if (!existsSync(brandPath)) return empty;
  const doc = readDoc(brandPath);
  const lift = (namespace: 'site' | 'project', keys: readonly string[]) => {
    const out: Record<string, string> = {};
    for (const key of keys) {
      const value = doc.getIn([namespace, 'options', key]);
      if (typeof value === 'string' && value) out[key] = value;
    }
    return out;
  };
  return {
    site: lift('site', BRAND_ASSET_KEYS.site),
    project: lift('project', BRAND_ASSET_KEYS.project),
  };
}

/** Reads `typst_template:` from `<instanceRoot>/journal.yml`: the journal's template, between
 *  the author's and oak's [R76]. It lives in journal.yml, which myst never reads, because
 *  brand.yml is a myst config layer and myst warns about keys it does not know. */
export function readJournalTypstTemplate(instanceRoot: string): string | undefined {
  return readJournalConfig(instanceRoot)?.typst_template || undefined;
}

/** Reads the author's own typst `template:` from `<paperRoot>/myst.yml`. The composed config
 *  cannot say who set it, since compose always stamps one [R82], so the override check
 *  [R76] reads it here. Undefined when absent or unreadable; that is another check's finding. */
export function readAuthorTypstTemplate(paperRoot: string): string | undefined {
  const authorPath = join(paperRoot, 'myst.yml');
  if (!existsSync(authorPath)) return undefined;
  let config: unknown;
  try {
    config = readDoc(authorPath).toJS();
  } catch {
    return undefined;
  }
  const exports = (config as { project?: { exports?: unknown } } | null)?.project?.exports;
  if (!Array.isArray(exports)) return undefined;
  const typst = exports.find(
    (e): e is Record<string, unknown> =>
      !!e && typeof e === 'object' && (e['format'] === 'typst' || e['id'] === 'typst-pdf'),
  );
  const template = typst?.['template'];
  return typeof template === 'string' && template ? template : undefined;
}

/** Pass 1: replaces any `extends:` with oak's chain. A migrated paper may still carry old URL
 *  pins. */
export function setExtends(doc: Document, chain: string[]): void {
  if (chain.length === 0) doc.delete('extends');
  else doc.set('extends', chain);
}

/** Pass 2: merges compose's additions: `project.exports`, `project.downloads`, `site.template`,
 *  and single asset keys under `site.options` and `project.options` [R62]. Keys are set one by
 *  one so the author's other options, and the `oaktree-sapling` key, survive; a download is
 *  appended unless the author declares its id. */
export function applyOwnOverride(doc: Document, override: OwnOverride): void {
  if (override.project?.exports) {
    doc.setIn(['project', 'exports'], override.project.exports);
  }
  for (const download of override.project?.downloads ?? []) {
    const existing = doc.getIn(['project', 'downloads']);
    if (existing === undefined) {
      doc.setIn(['project', 'downloads'], [download]);
    } else if (isSeq(existing)) {
      const ids = (existing.toJSON() as Array<{ id?: unknown }>).map((d) => d?.id);
      if (!ids.includes(download.id)) existing.add(doc.createNode(download));
    }
  }
  if (override.project?.options) {
    for (const [key, value] of Object.entries(override.project.options)) {
      doc.setIn(['project', 'options', key], value);
    }
  }
  if (override.site?.template) {
    doc.setIn(['site', 'template'], override.site.template);
  }
  if (override.site?.options) {
    for (const [key, value] of Object.entries(override.site.options)) {
      doc.setIn(['site', 'options', key], value);
    }
  }
}
